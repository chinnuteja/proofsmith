def _excluded_ids() -> set[str]:
    path = REPO / "data" / "trackB" / "EXCLUDED.md"
    if not path.is_file():
        return set()
    found: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            found.add(line[3:].strip())
    return found


