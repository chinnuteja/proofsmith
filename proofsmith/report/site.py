from jinja2 import Environment, FileSystemLoader

from proofsmith.config import REPO, RESULTS, RUNS, SITE

TEMPLATE_DIR = Path(__file__).resolve().parent / "templates"
STATIC_DIR = Path(__file__).resolve().parent / "static"


def format_number(value: object) -> str:
    """Format a JSON value the way the site prints it.

    Browser checks compare element text to this function, so every rendered
    data-source value must go through it.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return format(value, ".12g")
    if value is None:
        return ""
    return str(value)


def git_short_sha() -> str:
    try:
        proc = subprocess.run(
            ["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            check=True,
            text=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"
    sha = proc.stdout.strip()
    return sha or "unknown"


def _load_toolchain() -> dict:
    path = RESULTS / "toolchain.json"
    if not path.is_file():
        return {"clang_version": "UNKNOWN", "probes": []}
    return json.loads(path.read_text(encoding="utf-8"))


_ROW_LABELS = (
    ("buggy", "buggy"),
    ("timing_backoff", "timing backoff"),
    ("scoped_cancel", "ByteAsk's fix (scoped_lock in cancel)"),
    ("consistent_order", "consistent lock order"),
)

_CELL_LABELS = {
    "ctest": "existing tests (ctest)",
    "stress": "stress repro ×20",
    "verifier": "Proofsmith check ×20",
}


def _pointer_token(key: str) -> str:
    return key.replace("~", "~0").replace("/", "~1")


def _load_demo() -> dict | None:
    path = RESULTS / "demo" / "orderd.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _demo_rows(payload: dict) -> list[dict]:
    rows = []
    for key, label in _ROW_LABELS:
        row = payload["rows"][key]
        cells = []
        for name, left_key, right_key in (
            ("ctest", "passed", "total"),
            ("stress", "fails", "n"),
            ("verifier", "fails", "n"),
        ):
            block = row[name]
            left = block[left_key]
            right = block[right_key]
            if name == "ctest":
                pill = "pill-pass" if left == right else "pill-fail"
            else:
                pill = "pill-pass" if left == 0 else "pill-fail"
            base = f"results/demo/orderd.json#/rows/{key}/{name}"
            cells.append(
                {
                    "name": name,
                    "label": _CELL_LABELS[name],
                    "pill": pill,
                    "left": left,
                    "right": right,
                    "left_source": f"{base}/{left_key}",
                    "right_source": f"{base}/{right_key}",
                }
            )
        rows.append({"id": key, "label": label, "cells": cells})
    return rows


def _render_demo(env: Environment, git_sha: str) -> None:
    payload = _load_demo()
    if payload is None:
        return
    files = payload.get("verifier", {}).get("files", {})
    harness_sha = files.get("harness/harness.cpp", "")
    html = env.get_template("demo.html.j2").render(
        show_demo=True,
        show_runs=bool(_load_run_summaries()),
        show_verifiers=bool(_load_verifiers()),
        harness_label=_harness_label(payload),
        git_sha=git_sha,
        issue=payload["issue"],
        oracle=payload.get("oracle", ""),
        verifier=payload["verifier"],
        strip=payload.get("strip") or [],
        harness_sha=harness_sha,
        harness_pointer=_pointer_token("harness/harness.cpp"),
        rows=_demo_rows(payload),
        raw_report=payload.get("raw_report_buggy", ""),
    )
    demo_dir = SITE / "demo"
    demo_dir.mkdir(parents=True, exist_ok=True)
    (demo_dir / "index.html").write_text(html, encoding="utf-8", newline="\n")


def _harness_label(payload: dict) -> str:
    if payload.get("harness_source") == "proofsmith":
        return "Generated by Proofsmith (deepseek-v4-pro)"
    return "Reference harness (hand-written)"


def _load_verifiers() -> list[dict]:
    root = RESULTS / "verifiers"
    if not root.is_dir():
        return []
    found: list[dict] = []
    for path in sorted(root.glob("*/proofsmith.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if isinstance(data, dict):
            data["_instance_id"] = path.parent.name
            found.append(data)
    return found


def _run_id_from_trajectory(trajectory: object) -> str:
    if not isinstance(trajectory, str) or not trajectory:
        return ""
    parts = Path(trajectory).parts
    if len(parts) >= 2 and parts[0] == "runs":
        return parts[1]
    return ""


def _file_rows(instance_id: str, files: object) -> list[dict]:
    if not isinstance(files, dict):
        return []
    rows = []
    for name in sorted(files):
        pointer = _pointer_token(str(name))
        rows.append(
            {
                "name": name,
                "digest": files[name],
                "source": f"results/verifiers/{instance_id}/proofsmith.json#/files/{pointer}",
            }
        )
    return rows


def _strip(payload: dict) -> list[bool]:
    if payload.get("status") != "accepted":
        return []
    runtime = payload.get("runtime") or {}
    try:
        fails = int(runtime.get("fails") or 0)
        count = int(runtime.get("n") or 0)
    except (TypeError, ValueError):
        return []
    if count <= 0:
        return []
    red = min(max(fails, 0), count)
    return [True] * red + [False] * (count - red)


def _harness_source_text(instance_id: str) -> str:
    root = RESULTS / "verifiers" / instance_id / "bundle" / "harness"
    if not root.is_dir():
        return ""
    chunks: list[str] = []
    for path in sorted(item for item in root.rglob("*") if item.is_file()):
        rel = path.relative_to(root).as_posix()
        body = path.read_text(encoding="utf-8", errors="replace")
        chunks.append(f"// {rel}\n{body.rstrip()}\n")
    return "\n".join(chunks)


def _status_class(status: str) -> str:
    if status == "accepted":
        return "pill-pass"
    if status == "abstained":
        return "pill-warn"
    if status in {"error", "skipped"}:
        return "pill-fail"
    return "pill-info"


def _render_verifiers(env: Environment, git_sha: str, verifiers: list[dict]) -> None:
    if not verifiers:
        return
    show_demo = _load_demo() is not None
    show_runs = bool(_load_run_summaries())
    rows = []
    for item in verifiers:
        instance_id = str(item.get("_instance_id") or item.get("instance_id") or "")
        status = str(item.get("status") or "")
        rows.append(
            {
                "id": instance_id,
                "status": status,
                "pill": _status_class(status),
                "source": f"results/verifiers/{instance_id}/proofsmith.json#/status",
            }
        )
    page = env.get_template("verifiers.html.j2").render(
        git_sha=git_sha,
        show_demo=show_demo,
        show_runs=show_runs,
        show_verifiers=True,
        rows=rows,
    )
    dest = SITE / "verifiers"
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "index.html").write_text(page, encoding="utf-8", newline="\n")
    for item in verifiers:
        instance_id = str(item.get("_instance_id") or item.get("instance_id") or "")
        run_id = _run_id_from_trajectory(item.get("trajectory"))
        html = env.get_template("verifier.html.j2").render(
            git_sha=git_sha,
            show_demo=show_demo,
            show_runs=show_runs,
            show_verifiers=True,
            instance_id=instance_id,
            status=str(item.get("status") or ""),
            oracle=item.get("oracle"),
            signature=item.get("signature"),
            abstain_reason=item.get("abstain_reason"),
            runtime=item.get("runtime") or {},
            cost=item.get("cost_usd"),
            wall=item.get("wall_s"),
            strip=_strip(item),
            files=_file_rows(instance_id, item.get("files")),
            harness_text=_harness_source_text(instance_id),
            run_id=run_id,
            pill=_status_class(str(item.get("status") or "")),
        )
        folder = dest / instance_id
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "index.html").write_text(html, encoding="utf-8", newline="\n")


def _status_pill(status: str) -> str:
    if status == "finished":
        return "pass"
    if status == "abstained":
        return "warn"
    if status in {"error", "budget_exhausted"}:
        return "fail"
    return "info"


def _load_run_summaries() -> list[dict]:
    if not RUNS.is_dir():
        return []
    found: list[dict] = []
    for path in sorted(RUNS.glob("*/summary.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if not isinstance(data, dict):
            continue
        data.setdefault("run_id", path.parent.name)
        data["pill"] = _status_pill(str(data.get("status") or ""))
        found.append(data)
    return found


def _load_events(run_id: str) -> list[dict]:
    path = RUNS / run_id / "trajectory.jsonl"
    if not path.is_file():
        return []
    events: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return events


def _run_steps(events: list[dict]) -> list[dict]:
    grouped: dict[int, dict] = {}
    for event in events:
        kind = event.get("type")
        if kind not in {"llm_response", "tool_call", "tool_result"}:
            continue
        step = int(event.get("step") or 0)
        bucket = grouped.setdefault(
            step,
            {"step": step, "content": "", "calls": [], "results": []},
        )
        if kind == "llm_response":
            bucket["content"] = event.get("content") or ""
        elif kind == "tool_call":
            bucket["calls"].append(
                {
                    "name": event.get("name") or "",
                    "arguments": json.dumps(event.get("arguments") or {}, indent=2, ensure_ascii=False),
                }
            )
        else:
            bucket["results"].append(
                {
                    "name": event.get("name") or "tool",
                    "output": event.get("output") or "",
                }
            )
    return [grouped[key] for key in sorted(grouped)]


def _copy_run_data(runs: list[dict]) -> None:
    dest_root = SITE / "data" / "runs"
    dest_root.mkdir(parents=True, exist_ok=True)
    for run in runs:
        run_id = str(run.get("run_id") or "")
        source = RUNS / run_id / "summary.json"
        if source.is_file():
            shutil.copyfile(source, dest_root / f"{run_id}.json")


def _render_runs(env: Environment, git_sha: str, runs: list[dict]) -> None:
    if not runs:
        return
    runs_dir = SITE / "runs"
    runs_dir.mkdir(parents=True, exist_ok=True)
    index = env.get_template("runs.html.j2").render(
        git_sha=git_sha,
        show_demo=_load_demo() is not None,
        show_runs=True,
        show_verifiers=bool(_load_verifiers()),
        runs=runs,
    )
    (runs_dir / "index.html").write_text(index, encoding="utf-8", newline="\n")
    for run in runs:
        run_id = str(run["run_id"])
        steps = _run_steps(_load_events(run_id))
        tokens = float(run.get("tokens") or 0)
        maximum = float(run.get("max_total_tokens") or 0)
        pct = 0.0 if maximum <= 0 else min(100.0, tokens / maximum * 100.0)
        html = env.get_template("run.html.j2").render(
            git_sha=git_sha,
            show_demo=_load_demo() is not None,
            show_runs=True,
            show_verifiers=bool(_load_verifiers()),
            summary=run,
            steps=steps,
            pill=run.get("pill") or "info",
            token_pct=f"{pct:.4f}",
        )
        page = runs_dir / run_id
        page.mkdir(parents=True, exist_ok=True)
        (page / "index.html").write_text(html, encoding="utf-8", newline="\n")


