def build_site() -> None:
    SITE.mkdir(parents=True, exist_ok=True)
    for source, destination in ((RESULTS / "tool-demo/orderd", SITE / "gate"),
                                (RESULTS / "tool-demo/catch2/fixed", SITE / "upstream")):
        if (source / "index.html").is_file():
            shutil.copytree(source, destination, dirs_exist_ok=True)
    shutil.copyfile(STATIC_DIR / "site.css", SITE / "site.css")
    payload = _load_toolchain()
    probes = []
    for item in payload.get("probes", []):
        rel = item.get("output_path") or ""
        body = ""
        if rel:
            fixture = REPO / rel
            if fixture.is_file():
                body = fixture.read_text(encoding="utf-8", errors="replace")
        ok = bool(item.get("ok"))
        probes.append(
            {
                **item,
                "output": body,
                "pill": "pill-pass" if ok else "pill-fail",
                "pill_text": "pass" if ok else "fail",
            }
        )
    env = Environment(loader=FileSystemLoader(TEMPLATE_DIR), autoescape=True)
    env.filters["fmt"] = format_number
    trackb = _load_trackb()
    tracka = _load_tracka()
    dryrun = _load_dryrun()
    env.globals["show_trackb"] = trackb is not None
    env.globals["show_tracka"] = tracka is not None
    env.globals["show_eval"] = dryrun is not None
    env.globals["show_results"] = (RESULTS / "summary.json").is_file()
    sha = git_short_sha()
    runs = _load_run_summaries()
    verifiers = _load_verifiers()
    show_demo = _load_demo() is not None
    show_runs = bool(runs)
    show_verifiers = bool(verifiers)
    html = env.get_template("index.html.j2").render(
        clang_version=payload.get("clang_version", "UNKNOWN"),
        probes=probes,
        git_sha=sha,
        show_demo=show_demo,
        show_runs=show_runs,
        show_verifiers=show_verifiers,
    )
    (SITE / "index.html").write_text(html, encoding="utf-8", newline="\n")
    _render_demo(env, sha)
    _copy_run_data(runs)
    _render_runs(env, sha, runs)
    _render_verifiers(env, sha, verifiers)
    _render_trackb(env, sha, trackb)
    _render_tracka(env, sha, tracka)
